public class Day17 {
    public static void main(String[] args) {

    // Operator Penugasan (=, +=, -=, dll).
      
        int a = 10;

        a += 5;
        System.out.println("Setelah += : " + a);

        a -= 3;
        System.out.println("Setelah -= : " + a);

        a *= 2;
        System.out.println("Setelah *= : " + a);

        a /= 4;
        System.out.println("Setelah /= : " + a);

        a %= 3;
        System.out.println("Setelah %= : " + a);
    }
}
